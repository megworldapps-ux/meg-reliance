/* =========================================================
   SETTINGS
========================================================= */

const groupAlumniCardsPerPage = 10;

let groupAlumniCurrentPage = 1;

let groupAlumniCurrentFilter = "All";

let groupAlumniSearchText = "";


/* =========================================================
   ELEMENTS
========================================================= */

const groupAlumniGrid =
    document.getElementById(
        "groupAlumniGrid"
    );


const groupAlumniPagination =
    document.getElementById(
        "groupAlumniPagination"
    );


const groupAlumniPrev =
    document.getElementById(
        "groupAlumniPrev"
    );


const groupAlumniNext =
    document.getElementById(
        "groupAlumniNext"
    );


const groupAlumniSearch =
    document.getElementById(
        "groupAlumniSearch"
    );


const groupAlumniResultCount =
    document.getElementById(
        "groupAlumniResultCount"
    );


const groupAlumniFilters =
    document.querySelectorAll(
        ".group-alumni-filter"
    );


/* =========================================================
   FILTER
========================================================= */

function getGroupAlumniFilteredData() {

    return groupAlumniData.filter(
        function(alumni) {

            const filterMatch =
                groupAlumniCurrentFilter === "All" ||
                alumni.domain === groupAlumniCurrentFilter;


            const searchableText =
                (
                    alumni.name +
                    " " +
                    alumni.role +
                    " " +
                    alumni.domain
                ).toLowerCase();


            const searchMatch =
                searchableText.includes(
                    groupAlumniSearchText.toLowerCase()
                );


            return filterMatch && searchMatch;

        }
    );

}


/* =========================================================
   CREATE CARD
========================================================= */

function createGroupAlumniCard(alumni) {

    const card =
        document.createElement("div");


    card.className =
        "group-alumni-card";


    card.innerHTML = `

        <div class="group-alumni-card-image">

            <img
                src="${alumni.image}"
                alt="${alumni.name}"
                loading="lazy"
                onerror="
                    this.src='images/alumni-placeholder.jpg'
                "
            >

            <div
                class="group-alumni-card-overlay"
            ></div>

        </div>


        <div class="group-alumni-domain">
            ${alumni.domain}
        </div>


        <div class="group-alumni-card-content">

            <h3>
                ${alumni.name}
            </h3>

            <p>
                ${alumni.role}
            </p>


            

        </div>


       

    `;


    return card;

}


/* =========================================================
   SHOW PAGE
========================================================= */

function showGroupAlumniPage() {

    const filteredData =
        getGroupAlumniFilteredData();


    const totalPages =
        Math.ceil(
            filteredData.length /
            groupAlumniCardsPerPage
        );


    if (
        groupAlumniCurrentPage > totalPages &&
        totalPages > 0
    ) {

        groupAlumniCurrentPage =
            totalPages;

    }


    if (totalPages === 0) {

        groupAlumniCurrentPage = 1;

    }


    const startIndex =
        (
            groupAlumniCurrentPage - 1
        ) *
        groupAlumniCardsPerPage;


    const endIndex =
        startIndex +
        groupAlumniCardsPerPage;


    const pageData =
        filteredData.slice(
            startIndex,
            endIndex
        );


    /* Clear */

    groupAlumniGrid.innerHTML = "";


    /* No results */

    if (pageData.length === 0) {

        groupAlumniGrid.innerHTML = `

            <div class="group-alumni-no-results">
                No alumni found.
            </div>

        `;

        groupAlumniResultCount.textContent =
            "0";

    }


    /* Add cards */

    else {

        pageData.forEach(
            function(alumni) {

                const card =
                    createGroupAlumniCard(
                        alumni
                    );

                groupAlumniGrid.appendChild(
                    card
                );

            }
        );


        groupAlumniResultCount.textContent =
            pageData.length;

    }


    /* Pagination */

    createGroupAlumniPagination(
        totalPages
    );


    /* Arrow buttons */

    groupAlumniPrev.disabled =
        groupAlumniCurrentPage === 1;


    groupAlumniNext.disabled =
        groupAlumniCurrentPage === totalPages ||
        totalPages === 0;

}


/* =========================================================
   PAGINATION
========================================================= */

function createGroupAlumniPagination(
    totalPages
) {

    groupAlumniPagination.innerHTML = "";


    if (totalPages <= 1) {

        return;

    }


    let startPage =
        Math.max(
            1,
            groupAlumniCurrentPage - 2
        );


    let endPage =
        Math.min(
            totalPages,
            startPage + 4
        );


    if (
        endPage - startPage < 4
    ) {

        startPage =
            Math.max(
                1,
                endPage - 4
            );

    }


    /* First page */

    if (startPage > 1) {

        addGroupAlumniPage(1);


        if (startPage > 2) {

            addGroupAlumniDots();

        }

    }


    /* Middle pages */

    for (
        let page = startPage;
        page <= endPage;
        page++
    ) {

        addGroupAlumniPage(page);

    }


    /* Last page */

    if (endPage < totalPages) {

        if (
            endPage <
            totalPages - 1
        ) {

            addGroupAlumniDots();

        }


        addGroupAlumniPage(
            totalPages
        );

    }

}


/* =========================================================
   PAGE BUTTON
========================================================= */

function addGroupAlumniPage(page) {

    const button =
        document.createElement("button");


    button.type =
        "button";


    button.className =
        "group-alumni-page";


    button.textContent =
        page;


    if (
        page === groupAlumniCurrentPage
    ) {

        button.classList.add(
            "active"
        );

    }


    button.addEventListener(
        "click",
        function() {

            groupAlumniCurrentPage =
                page;

            showGroupAlumniPage();

            scrollToGroupAlumni();

        }
    );


    groupAlumniPagination.appendChild(
        button
    );

}


/* =========================================================
   DOTS
========================================================= */

function addGroupAlumniDots() {

    const dots =
        document.createElement("span");


    dots.className =
        "group-alumni-dots";


    dots.textContent =
        "...";


    groupAlumniPagination.appendChild(
        dots
    );

}


/* =========================================================
   NEXT
========================================================= */

groupAlumniNext.addEventListener(
    "click",
    function() {

        const filteredData =
            getGroupAlumniFilteredData();


        const totalPages =
            Math.ceil(
                filteredData.length /
                groupAlumniCardsPerPage
            );


        if (
            groupAlumniCurrentPage <
            totalPages
        ) {

            groupAlumniCurrentPage++;

            showGroupAlumniPage();

            scrollToGroupAlumni();

        }

    }
);


/* =========================================================
   PREVIOUS
========================================================= */

groupAlumniPrev.addEventListener(
    "click",
    function() {

        if (
            groupAlumniCurrentPage > 1
        ) {

            groupAlumniCurrentPage--;

            showGroupAlumniPage();

            scrollToGroupAlumni();

        }

    }
);


/* =========================================================
   SCROLL
========================================================= */

function scrollToGroupAlumni() {

    const section =
        document.querySelector(
            ".group-alumni-section"
        );


    if (!section) {

        return;

    }


    const top =
        section.getBoundingClientRect().top +
        window.pageYOffset -
        80;


    window.scrollTo({

        top: top,

        behavior: "smooth"

    });

}


/* =========================================================
   FILTER BUTTONS
========================================================= */

groupAlumniFilters.forEach(
    function(button) {

        button.addEventListener(
            "click",
            function() {


                groupAlumniFilters.forEach(
                    function(item) {

                        item.classList.remove(
                            "active"
                        );

                    }
                );


                button.classList.add(
                    "active"
                );


                groupAlumniCurrentFilter =
                    button.dataset.filter;


                groupAlumniCurrentPage =
                    1;


                showGroupAlumniPage();

            }
        );

    }
);


/* =========================================================
   SEARCH
========================================================= */

groupAlumniSearch.addEventListener(
    "input",
    function() {

        groupAlumniSearchText =
            this.value.trim();


        groupAlumniCurrentPage =
            1;


        showGroupAlumniPage();

    }
);


/* =========================================================
   INITIAL LOAD
========================================================= */

showGroupAlumniPage();